import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from erdraw import ER, Schema
OUT = os.path.join(os.path.dirname(__file__), '..', 'content', 'figures')
def save(name, d):
    with open(os.path.join(OUT, name + '.svg'), 'w') as f:
        f.write(d.svg())

d = ER('Conference EER model (Mock endsem Q1)')
d.entity('CONFERENCE', 110, 110)
d.attr('CONFERENCE', 'Conf_key', -10, -70, key=True, parts=[('Acronym', -80, -35), ('Year', 80, -35)])
d.rel('HAS_TRACK', 110, 250, ident=True)
d.link('CONFERENCE', 'HAS_TRACK', '(1,N)', total=True)
d.entity('TRACK', 110, 390, weak=True)
d.link('TRACK', 'HAS_TRACK', '(1,1)', total=True)
d.attr('TRACK', 'Track_name', -20, 60, partial=True)
d.rel('SUBMITTED_TO', 320, 390)
d.link('TRACK', 'SUBMITTED_TO', '(0,N)')
d.entity('PAPER', 540, 390)
d.link('PAPER', 'SUBMITTED_TO', '(1,1)', total=True)
d.attr('PAPER', 'PaperID', -60, -60, key=True); d.attr('PAPER', 'Title', -110, 50)
d.entity('PERSON', 930, 90)
d.attr('PERSON', 'Email', -110, -20, key=True); d.attr('PERSON', 'Name', 0, -60); d.attr('PERSON', 'Affiliation', 120, -30, multi=True)
d.spec('sp', 930, 190, 'o'); d.sup('PERSON', 'sp')
d.entity('AUTHOR', 830, 300); d.entity('PC_MEMBER', 1060, 300)
d.sub('sp', 'AUTHOR'); d.sub('sp', 'PC_MEMBER')
d.rel('WRITES', 680, 270)
d.link('AUTHOR', 'WRITES', '(1,N)', total=True); d.link('PAPER', 'WRITES', '(1,N)', total=True)
d.attr('WRITES', 'Position', 0, -55)
d.rel('CONTACT', 690, 420)
d.link('PAPER', 'CONTACT', '(1,1)', total=True); d.link('AUTHOR', 'CONTACT', '(0,N)')
d.rel('OF_PAPER', 540, 530, ident=True)
d.link('PAPER', 'OF_PAPER', '(3,N)', total=True)
d.entity('REVIEW', 540, 660, weak=True)
d.link('REVIEW', 'OF_PAPER', '(1,1)', total=True)
d.attr('REVIEW', 'Review_no', -120, 0, partial=True); d.attr('REVIEW', 'Score', -60, 60); d.attr('REVIEW', 'Comments', 50, 60)
d.rel('WRITTEN_BY', 840, 660)
d.link('REVIEW', 'WRITTEN_BY', '(1,1)', total=True); d.link('PC_MEMBER', 'WRITTEN_BY', '(0,N)')
save('dna-mock1-conference', d)

s = Schema('Conference relational schema (Mock endsem Q2)')
s.rel('CONFERENCE', ['Acronym*', 'Year*'])
s.rel('TRACK', ['Acronym*', 'Year*', 'Track_name*'])
s.rel('PAPER', ['PaperID*', 'Title', 'Acronym', 'Year', 'Track_name', 'Contact_email'])
s.rel('PERSON', ['Email*', 'Name'])
s.rel('PERSON_AFFILIATION', ['Email*', 'Affiliation*'], same_row=True)
s.rel('AUTHOR', ['Email*'])
s.rel('PC_MEMBER', ['Email*'], same_row=True)
s.rel('WRITES', ['PaperID*', 'Email*', 'Position'])
s.rel('REVIEW', ['PaperID*', 'Review_no*', 'Score', 'Comments', 'Reviewer_email'])
s.fk('TRACK.Acronym,Year', 'CONFERENCE.Acronym,Year')
s.fk('PAPER.Acronym,Year,Track_name', 'TRACK.Acronym,Year,Track_name')
s.fk('PAPER.Contact_email', 'AUTHOR.Email')
s.fk('PERSON_AFFILIATION.Email', 'PERSON.Email')
s.fk('AUTHOR.Email', 'PERSON.Email'); s.fk('PC_MEMBER.Email', 'PERSON.Email')
s.fk('WRITES.PaperID', 'PAPER.PaperID'); s.fk('WRITES.Email', 'AUTHOR.Email')
s.fk('REVIEW.PaperID', 'PAPER.PaperID'); s.fk('REVIEW.Reviewer_email', 'PC_MEMBER.Email')
save('dna-mock2-schema', s)
print('ok')
