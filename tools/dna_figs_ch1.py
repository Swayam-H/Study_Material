import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from erdraw import Schema

OUT = os.path.join(os.path.dirname(__file__), '..', 'content', 'figures')
def save(name, d):
    with open(os.path.join(OUT, name + '.svg'), 'w') as f:
        f.write(d.svg())

s = Schema('AIRLINE relational schema with its 12 foreign keys (Elmasri Fig 5.8)')
s.rel('AIRPORT', ['Airport_code*', 'Name', 'City', 'State'])
s.rel('FLIGHT', ['Flight_number*', 'Airline', 'Weekdays'], same_row=True)
s.rel('FLIGHT_LEG', ['Flight_number*', 'Leg_number*', 'Departure_airport_code', 'Scheduled_departure_time', 'Arrival_airport_code', 'Scheduled_arrival_time'])
s.rel('LEG_INSTANCE', ['Flight_number*', 'Leg_number*', 'Date*', 'Number_of_available_seats', 'Airplane_id', 'Departure_airport_code', 'Departure_time', 'Arrival_airport_code', 'Arrival_time'])
s.rel('FARE', ['Flight_number*', 'Fare_code*', 'Amount', 'Restrictions'])
s.rel('AIRPLANE_TYPE', ['Airplane_type_name*', 'Max_seats', 'Company'])
s.rel('CAN_LAND', ['Airplane_type_name*', 'Airport_code*'], same_row=True)
s.rel('AIRPLANE', ['Airplane_id*', 'Total_number_of_seats', 'Airplane_type'])
s.rel('SEAT_RESERVATION', ['Flight_number*', 'Leg_number*', 'Date*', 'Seat_number*', 'Customer_name', 'Customer_phone'])
s.fk('FLIGHT_LEG.Flight_number', 'FLIGHT.Flight_number')
s.fk('FLIGHT_LEG.Departure_airport_code', 'AIRPORT.Airport_code')
s.fk('FLIGHT_LEG.Arrival_airport_code', 'AIRPORT.Airport_code')
s.fk('LEG_INSTANCE.Flight_number,Leg_number', 'FLIGHT_LEG.Flight_number,Leg_number')
s.fk('LEG_INSTANCE.Airplane_id', 'AIRPLANE.Airplane_id')
s.fk('LEG_INSTANCE.Departure_airport_code', 'AIRPORT.Airport_code')
s.fk('LEG_INSTANCE.Arrival_airport_code', 'AIRPORT.Airport_code')
s.fk('FARE.Flight_number', 'FLIGHT.Flight_number')
s.fk('CAN_LAND.Airplane_type_name', 'AIRPLANE_TYPE.Airplane_type_name')
s.fk('CAN_LAND.Airport_code', 'AIRPORT.Airport_code')
s.fk('AIRPLANE.Airplane_type', 'AIRPLANE_TYPE.Airplane_type_name')
s.fk('SEAT_RESERVATION.Flight_number,Leg_number,Date', 'LEG_INSTANCE.Flight_number,Leg_number,Date')
save('dna-512-airline-schema', s)

s = Schema('Elmasri 5.15: foreign keys')
s.rel('SALESPERSON', ['Ssn*', 'Name', 'Start_year', 'Dept_no'])
s.rel('TRIP', ['Ssn', 'From_city', 'To_city', 'Departure_date', 'Return_date', 'Trip_id*'])
s.rel('EXPENSE', ['Trip_id*', 'Account#*', 'Amount'])
s.fk('TRIP.Ssn', 'SALESPERSON.Ssn'); s.fk('EXPENSE.Trip_id', 'TRIP.Trip_id')
save('dna-515-fk', s)

s = Schema('Elmasri 5.16: foreign keys')
s.rel('STUDENT', ['Ssn*', 'Name', 'Major', 'Bdate'])
s.rel('COURSE', ['Course#*', 'Cname', 'Dept'])
s.rel('ENROLL', ['Ssn*', 'Course#*', 'Quarter*', 'Grade'])
s.rel('BOOK_ADOPTION', ['Course#*', 'Quarter*', 'Book_isbn*'])
s.rel('TEXT', ['Book_isbn*', 'Book_title', 'Publisher', 'Author'])
s.fk('ENROLL.Ssn', 'STUDENT.Ssn'); s.fk('ENROLL.Course#', 'COURSE.Course#')
s.fk('BOOK_ADOPTION.Course#', 'COURSE.Course#'); s.fk('BOOK_ADOPTION.Book_isbn', 'TEXT.Book_isbn')
save('dna-516-fk', s)

s = Schema('Elmasri 5.17: foreign keys')
s.rel('CAR', ['Serial_no*', 'Model', 'Manufacturer', 'Price'])
s.rel('OPTION', ['Serial_no*', 'Option_name*', 'Price'])
s.rel('SALE', ['Salesperson_id*', 'Serial_no*', 'Date', 'Sale_price'])
s.rel('SALESPERSON', ['Salesperson_id*', 'Name', 'Phone'])
s.fk('OPTION.Serial_no', 'CAR.Serial_no'); s.fk('SALE.Serial_no', 'CAR.Serial_no'); s.fk('SALE.Salesperson_id', 'SALESPERSON.Salesperson_id')
save('dna-517-fk', s)
